package isolation

import (
	"crypto/ed25519"
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"errors"
	"os"
	"path/filepath"
	"testing"
	"time"
)

type releaseTokenVectorFile struct {
	Domain   string `json:"domain"`
	TestKeys map[string]struct {
		SeedHex         string `json:"seedHex"`
		PublicKeyBase64 string `json:"publicKeyBase64"`
	} `json:"testKeys"`
	Context struct {
		PublicKey   string `json:"publicKey"`
		Now         int64  `json:"now"`
		IsolationID string `json:"isolationId"`
		Generation  int    `json:"generation"`
		DeviceID    string `json:"deviceId"`
	} `json:"context"`
	Valid []struct {
		Description string `json:"description"`
		Payload     string `json:"payload"`
		Token       string `json:"token"`
	} `json:"valid"`
	Invalid []struct {
		Description   string `json:"description"`
		Token         string `json:"token"`
		Reason        string `json:"reason"`
		HighWaterWall int64  `json:"highWaterWall"`
	} `json:"invalid"`
	SmallOrderPublicKeysHex []string `json:"smallOrderPublicKeysHex"`
}

// The vectors file is shared with the API (releaseToken.test.ts) and was
// generated by a pure-Python RFC 8032 implementation, independent of both.
func loadReleaseTokenVectors(t *testing.T) releaseTokenVectorFile {
	t.Helper()
	data, err := os.ReadFile(filepath.Join("testdata", "release_token_vectors.json"))
	if err != nil {
		t.Fatalf("read vectors: %v", err)
	}
	var f releaseTokenVectorFile
	if err := json.Unmarshal(data, &f); err != nil {
		t.Fatalf("parse vectors: %v", err)
	}
	if len(f.Valid) == 0 || len(f.Invalid) == 0 || len(f.SmallOrderPublicKeysHex) == 0 {
		t.Fatal("vectors file is missing a section")
	}
	return f
}

func vectorKey(t *testing.T, f releaseTokenVectorFile, name string) (ed25519.PrivateKey, []byte) {
	t.Helper()
	k, ok := f.TestKeys[name]
	if !ok {
		t.Fatalf("no test key %q", name)
	}
	seed, err := hex.DecodeString(k.SeedHex)
	if err != nil {
		t.Fatal(err)
	}
	pub, err := base64.StdEncoding.DecodeString(k.PublicKeyBase64)
	if err != nil {
		t.Fatal(err)
	}
	priv := ed25519.NewKeyFromSeed(seed)
	if string(priv.Public().(ed25519.PublicKey)) != string(pub) {
		t.Fatalf("test key %q: public key does not match its seed", name)
	}
	return priv, pub
}

func vectorBinding(f releaseTokenVectorFile) ReleaseTokenBinding {
	return ReleaseTokenBinding{IsolationID: f.Context.IsolationID, Generation: f.Context.Generation, DeviceID: f.Context.DeviceID}
}

func TestReleaseTokenDomainMatchesVectors(t *testing.T) {
	f := loadReleaseTokenVectors(t)
	if f.Domain != releaseTokenDomain {
		t.Fatalf("domain = %q, vectors say %q", releaseTokenDomain, f.Domain)
	}
}

func TestReleaseTokenVectorsValid(t *testing.T) {
	f := loadReleaseTokenVectors(t)
	_, pub := vectorKey(t, f, f.Context.PublicKey)
	now := time.Unix(f.Context.Now, 0)
	for _, v := range f.Valid {
		t.Run(v.Description, func(t *testing.T) {
			if err := VerifyReleaseToken(v.Token, pub, vectorBinding(f), now, time.Time{}); err != nil {
				t.Fatalf("VerifyReleaseToken: %v", err)
			}
		})
	}
}

func TestReleaseTokenVectorsInvalid(t *testing.T) {
	f := loadReleaseTokenVectors(t)
	_, pub := vectorKey(t, f, f.Context.PublicKey)
	now := time.Unix(f.Context.Now, 0)
	for _, v := range f.Invalid {
		t.Run(v.Description, func(t *testing.T) {
			var high time.Time
			if v.HighWaterWall > 0 {
				high = time.Unix(v.HighWaterWall, 0)
			}
			err := VerifyReleaseToken(v.Token, pub, vectorBinding(f), now, high)
			if err == nil {
				t.Fatal("token accepted")
			}
			if got := ReleaseTokenRejectReason(err); got != v.Reason {
				t.Fatalf("reason = %q (%v), want %q", got, err, v.Reason)
			}
			if !errors.Is(err, ErrReleaseTokenInvalid) {
				t.Fatalf("error %v does not wrap ErrReleaseTokenInvalid", err)
			}
		})
	}
}

func TestReleaseTokenRejectsUnusablePublicKeys(t *testing.T) {
	f := loadReleaseTokenVectors(t)
	now := time.Unix(f.Context.Now, 0)
	token := f.Valid[0].Token
	keys := map[string][]byte{"nil": nil, "empty": {}, "31 bytes": make([]byte, 31), "33 bytes": make([]byte, 33)}
	for _, h := range f.SmallOrderPublicKeysHex {
		b, err := hex.DecodeString(h)
		if err != nil || len(b) != ed25519.PublicKeySize {
			t.Fatalf("bad small-order vector %q", h)
		}
		keys["small order "+h] = b
	}
	for name, key := range keys {
		t.Run(name, func(t *testing.T) {
			if ValidReleaseTokenPublicKey(key) {
				t.Fatal("ValidReleaseTokenPublicKey accepted the key")
			}
			err := VerifyReleaseToken(token, key, vectorBinding(f), now, time.Time{})
			if got := ReleaseTokenRejectReason(err); got != ReleaseTokenUnavailable {
				t.Fatalf("reason = %q (%v), want %q", got, err, ReleaseTokenUnavailable)
			}
		})
	}
	_, pub := vectorKey(t, f, "a")
	if !ValidReleaseTokenPublicKey(pub) {
		t.Fatal("a real public key was refused")
	}
}

// A token is bound to one episode at one generation, so the same string can
// never release a later generation or another episode.
func TestReleaseTokenBindsGenerationAndEpisode(t *testing.T) {
	f := loadReleaseTokenVectors(t)
	_, pub := vectorKey(t, f, "a")
	now := time.Unix(f.Context.Now, 0)
	token := f.Valid[0].Token
	b := vectorBinding(f)
	b.Generation++
	if got := ReleaseTokenRejectReason(VerifyReleaseToken(token, pub, b, now, time.Time{})); got != ReleaseTokenWrongGeneration {
		t.Fatalf("after an extend: reason = %q", got)
	}
	b = vectorBinding(f)
	b.IsolationID = "00000000-0000-4000-8000-000000000000"
	if got := ReleaseTokenRejectReason(VerifyReleaseToken(token, pub, b, now, time.Time{})); got != ReleaseTokenWrongEpisode {
		t.Fatalf("another episode: reason = %q", got)
	}
	b = vectorBinding(f)
	b.DeviceID = ""
	if got := ReleaseTokenRejectReason(VerifyReleaseToken(token, pub, b, now, time.Time{})); got != ReleaseTokenWrongDevice {
		t.Fatalf("no pinned device: reason = %q", got)
	}
}

func TestSmallOrderKeyListMatchesVectors(t *testing.T) {
	f := loadReleaseTokenVectors(t)
	if len(f.SmallOrderPublicKeysHex) != len(smallOrderEd25519Keys) {
		t.Fatalf("vectors list %d small-order keys, the agent %d", len(f.SmallOrderPublicKeysHex), len(smallOrderEd25519Keys))
	}
	for i, h := range f.SmallOrderPublicKeysHex {
		if hex.EncodeToString(smallOrderEd25519Keys[i]) != h {
			t.Fatalf("small-order key %d = %x, vectors say %s", i, smallOrderEd25519Keys[i], h)
		}
	}
}

func TestReleaseTokenRejectReasonOfOtherErrors(t *testing.T) {
	if got := ReleaseTokenRejectReason(nil); got != "" {
		t.Fatalf("nil: %q", got)
	}
	if got := ReleaseTokenRejectReason(errors.New("x")); got != "" {
		t.Fatalf("plain error: %q", got)
	}
}

// FuzzVerifyReleaseToken: arbitrary input never panics and is never accepted
// under a key nobody holds the private half of.
func FuzzVerifyReleaseToken(f *testing.F) {
	vf := releaseTokenVectorFile{}
	data, err := os.ReadFile(filepath.Join("testdata", "release_token_vectors.json"))
	if err == nil && json.Unmarshal(data, &vf) == nil {
		for _, v := range vf.Valid {
			f.Add(v.Token)
		}
		for _, v := range vf.Invalid {
			f.Add(v.Token)
		}
	}
	pub := make([]byte, ed25519.PublicKeySize)
	pub[0] = 0x5a // not small order; no known private key
	pub[31] = 0x11
	b := ReleaseTokenBinding{IsolationID: "6f1c2d3e-4b5a-4c6d-8e7f-0123456789ab", Generation: 3, DeviceID: "1a2b3c4d-5e6f-4a7b-8c9d-0e1f2a3b4c5d"}
	now := time.Unix(1767225600, 0)
	f.Fuzz(func(t *testing.T, token string) {
		if VerifyReleaseToken(token, pub, b, now, time.Time{}) == nil {
			t.Fatalf("accepted %q", token)
		}
	})
}
