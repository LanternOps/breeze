package biosconfig

import (
	"bytes"
	"context"
	"encoding/json"
	"os"
	"path/filepath"
	"testing"
)

// The goldens in testdata/wire are what the agent sends as
// details.vendorObservation; packages/shared/src/validators/wakeStatus.observation.test.ts
// parses the same files against the server schema. Regenerate with
// WAKE_WIRE_UPDATE=1 go test ./internal/biosconfig/ -run TestWireGoldens.

func withCommon(o *Observation) *Observation {
	o.Schema, o.NativeArch, o.DurationMs, o.CollectedWith = 1, "amd64", 812, "0.131.0"
	return o
}

// CheckWireGolden compares v's JSON with testdata/wire/<name>.json under dir.
func checkWireGolden(t *testing.T, dir, name string, v any) {
	t.Helper()
	got, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	got = append(got, '\n')
	path := filepath.Join(dir, "testdata", "wire", name+".json")
	if os.Getenv("WAKE_WIRE_UPDATE") == "1" {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s golden differs; regenerate with WAKE_WIRE_UPDATE=1\n got: %s\nwant: %s", name, got, want)
	}
	// Every key is present: decoding the golden back gives the same value.
	var back Observation
	dec := json.NewDecoder(bytes.NewReader(want))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&back); err != nil {
		t.Fatalf("%s golden does not decode strictly: %v", name, err)
	}
}

func TestWireGoldens(t *testing.T) {
	hp := newFakeRunner()
	hp.out[hpReadScript] = fixture(t, "hp", "doc-derived", "elitedesk.json")
	checkWireGolden(t, ".", "hp", withCommon(observer(t, DetectWith("HP", "EliteDesk 800 G6", VendorHP, hp.run)).Observe(context.Background())))

	hpAbsent := newFakeRunner()
	hpAbsent.out[hpReadScript] = fixture(t, "hp", "doc-derived", "consumer_absent.json")
	checkWireGolden(t, ".", "hp_absent", withCommon(observer(t, DetectWith("HP", "Pavilion", VendorHP, hpAbsent.run)).Observe(context.Background())))

	lenovo := newFakeRunner()
	lenovo.out[lenovoReadScript] = fixture(t, "lenovo", "doc-derived", "thinkpad.json")
	lenovo.out[lenovoSelectionsScript] = selectionsReply(t, map[string]string{
		"WakeOnLAN":           "Disable,ACOnly,ACandBattery,Enable",
		"WakeOnLANDock":       "Disable,Enable",
		"AfterPowerLoss":      "PowerOn,PowerOff,LastState",
		"PXEIPV4NetworkStack": "Disable,Enable",
	})
	checkWireGolden(t, ".", "lenovo", withCommon(observer(t, DetectWith("LENOVO", "20U9CTO1WW", VendorLenovo, lenovo.run)).Observe(context.Background())))
	// lenovo_panic is generated by wakeconfig's TestObserverPanicKeepsCommonFields,
	// through the production observer, so it is the shape a panic really sends.
}
