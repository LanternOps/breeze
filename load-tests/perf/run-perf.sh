#!/usr/bin/env bash
# load-tests/perf/run-perf.sh — one measured perf run (scaling W07, #8146).
#   run-perf.sh --profile nightly-200|smoke --out-dir <dir> [--label clean|inject]
# Brings up this checkout's wt-stack, runs the W02 simulator under sample.sh, and
# writes $OUT/{idle.csv,samples.csv,agentsim.json,hardware.json,stack.json,kpi.json}.
# Exit: 0 ok, 1 a step failed, 2 invalid run (refused .env, failed acceptance), 64 usage.
# Lab values are exported in this shell only; nothing here is a code default.
set -euo pipefail

# --- Profiles (D12). The simulator's --duration is the whole run from the first
# agent start; its steady window opens at ceil(agents/ramp) + warmup, so
#   duration = ceil(agents/ramp)s + warmup + window.
# name        agents  ramp(/s)  warmup(s)  window(s)  commands/min  ws    start
#   nightly-200   200      10       180       1200          30       true  warm   -> 23m20s
#   smoke          20      10        60        240          30       true  warm   -> 5m2s
profile_params() {
  case "$1" in
    nightly-200) AGENTS=200; RAMP=10; WARMUP_S=180; WINDOW_S=1200; CPM=30; WS=true; START=warm ;;
    smoke)       AGENTS=20;  RAMP=10; WARMUP_S=60;  WINDOW_S=240;  CPM=30; WS=true; START=warm ;;
    *) return 1 ;;
  esac
}

# Seconds -> Go duration string: 180 -> 3m, 1400 -> 23m20s, 302 -> 5m2s.
go_dur() {
  local s="$1" out="" m r
  m=$((s / 60)); r=$((s % 60))
  [ "$m" -gt 0 ] && out="${m}m"
  if [ "$r" -gt 0 ] || [ "$m" -eq 0 ]; then out="${out}${r}s"; fi
  echo "$out"
}

usage() { echo "usage: run-perf.sh --profile nightly-200|smoke --out-dir <dir> [--label clean|inject]" >&2; exit 64; }

PROFILE=""; OUT=""; LABEL="clean"
while [ $# -gt 0 ]; do
  case "$1" in
    --profile) PROFILE="${2:-}"; shift 2 || usage ;;
    --out-dir) OUT="${2:-}"; shift 2 || usage ;;
    --label)   LABEL="${2:-}"; shift 2 || usage ;;
    *) usage ;;
  esac
done
[ -n "$PROFILE" ] && [ -n "$OUT" ] || usage
profile_params "$PROFILE" || { echo "run-perf: unknown profile '$PROFILE'" >&2; usage; }
case "$LABEL" in clean|inject) ;; *) echo "run-perf: --label must be clean or inject" >&2; usage ;; esac

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
SIM="$REPO/load-tests/agentsim"
mkdir -p "$OUT"
OUT="$(cd "$OUT" && pwd)"

# Duration: ramp (rounded up) + warmup + window.
RAMP_S=$(( (AGENTS + RAMP - 1) / RAMP ))
DURATION="$(go_dur $((RAMP_S + WARMUP_S + WINDOW_S)))"
WARMUP="$(go_dur "$WARMUP_S")"

# --- 1. Root .env. wt-stack requires one (compose.ts); never reuse a real one.
MARKER='# generated by load-tests/perf/run-perf.sh'
ENV_FILE="$REPO/.env"
if [ -e "$ENV_FILE" ] && [ "$(head -n1 "$ENV_FILE")" != "$MARKER" ]; then
  echo "run-perf: $ENV_FILE exists and was not generated by this script; refusing to run (it may hold real provider keys the lab stack must never see). Move it away first." >&2
  exit 2
fi

cleanup() {
  local rc=$?
  trap - EXIT
  set +e
  ( cd "$REPO" && pnpm wt-stack down ) || echo "run-perf: pnpm wt-stack down failed; check for a leftover stack" >&2
  rm -rf "$SIM/.state"
  rm -f "$ENV_FILE"
  exit "$rc"
}
trap cleanup EXIT

METRICS_SCRAPE_TOKEN="$(openssl rand -hex 24)"
export METRICS_SCRAPE_TOKEN

# Generate the throwaway .env from the example: secret-looking values become random.
SECRET_KEY_RE='(^|_)(SECRET|PASSWORD|PASS|TOKEN|PEPPER|KEY|KEYRING)$'
{
  echo "$MARKER"
  seen_https=0
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in
      ''|'#'*) echo "$line"; continue ;;
    esac
    key="${line%%=*}"
    val="${line#*=}"
    if [ "$key" = "FORCE_HTTPS" ]; then
      echo "FORCE_HTTPS=false"; seen_https=1
    elif [ "$key" = "METRICS_SCRAPE_TOKEN" ]; then
      echo "METRICS_SCRAPE_TOKEN=$METRICS_SCRAPE_TOKEN"
    elif [[ "$key" =~ $SECRET_KEY_RE ]] && [ -n "$val" ]; then
      echo "$key=$(openssl rand -hex 24)"
    elif [[ "$val" =~ ^([A-Za-z][A-Za-z0-9+.-]*://[^:/@]+:)[^@]+(@.*)$ ]]; then
      echo "$key=${BASH_REMATCH[1]}$(openssl rand -hex 24)${BASH_REMATCH[2]}"
    else
      echo "$line"
    fi
  done <"$REPO/.env.example"
  [ "$seen_https" = 1 ] || echo "FORCE_HTTPS=false"
} >"$ENV_FILE"
chmod 600 "$ENV_FILE"

# --- 2. Stack.
export AGENT_ENROLL_RATE_LIMIT=5000 FORCE_HTTPS=false BREEZE_ADMISSION_MODE=observe
echo "run-perf: profile=$PROFILE label=$LABEL duration=$DURATION out=$OUT" >&2
echo "$LABEL" >"$OUT/label.txt"
( cd "$REPO" && pnpm wt-stack up )

# --- 3. Lab setup (W06's scripts, unchanged).
mkdir -p "$SIM/.state"
chmod 700 "$SIM/.state"
( umask 077; "$SIM/lab-setup.sh" >"$SIM/.state/lab.env" )

# --- 4. Idle sample, no agents.
SAMPLER_PID=""
stop_sampler() {
  if [ -n "$SAMPLER_PID" ]; then
    kill "$SAMPLER_PID" 2>/dev/null || true
    wait "$SAMPLER_PID" 2>/dev/null || true
    SAMPLER_PID=""
  fi
}
"$HERE/sample.sh" "$OUT/idle.csv" &
SAMPLER_PID=$!
sleep "${IDLE_SECONDS:-120}"
stop_sampler

# --- 5. Measured run. Every profile flag is explicit so simulator default
# changes cannot move the baseline; a repeated flag takes its last value, so
# --report here beats run.sh's timestamped default.
"$HERE/sample.sh" "$OUT/samples.csv" &
SAMPLER_PID=$!
sim_rc=0
"$SIM/run.sh" --agents "$AGENTS" --ramp "$RAMP" --warmup "$WARMUP" --duration "$DURATION" \
  --start "$START" --report "$OUT/agentsim.json" --ws="$WS" --commands-per-minute "$CPM" || sim_rc=$?
stop_sampler
if [ "$sim_rc" -ne 0 ]; then
  echo "run-perf: simulator exited $sim_rc" >&2
  exit 1
fi

# --- 6. Acceptance: a failing report means the run measured something else.
if ! "$SIM/check-acceptance.sh" report "$OUT/agentsim.json"; then
  echo "run-perf: check-acceptance.sh report failed; run is invalid" >&2
  exit 2
fi

# --- 7. Hardware fingerprint (D9) and stack profile, then the KPI record.
PROC="${PERF_PROC_DIR:-/proc}"
KERNEL="$(uname -r)"
DOCKER_VERSION="$(docker version --format '{{.Server.Version}}' 2>/dev/null || echo unknown)"
if [ "$(uname -s)" = "Linux" ]; then
  CPU_MODEL="$(awk -F': *' '/^model name/ {print $2; exit}' "$PROC/cpuinfo")"
  CPUS="$(nproc)"
  MEM_KB="$(awk '/^MemTotal:/ {print $2; exit}' "$PROC/meminfo")"
  MEM_GIB=$((MEM_KB / 1048576))
  GRADE=true
else
  # Not baseline-grade: the figures describe the Docker VM, not a fixed machine.
  read -r CPUS MEM_BYTES < <(docker info --format '{{.NCPU}} {{.MemTotal}}')
  MEM_GIB=$((MEM_BYTES / 1073741824))
  CPU_MODEL="$(sysctl -n machdep.cpu.brand_string)"
  GRADE=false
fi
jq -n --arg m "$CPU_MODEL" --argjson c "$CPUS" --argjson g "$MEM_GIB" --arg k "$KERNEL" --arg d "$DOCKER_VERSION" --argjson b "$GRADE" \
  '{cpuModel: $m, cpus: $c, memGiB: $g, kernel: $k, dockerVersion: $d, baselineGrade: $b}' >"$OUT/hardware.json"
echo '{"profile":"wt-stack-dev","role":"all","admissionMode":"observe","e2eMode":true}' >"$OUT/stack.json"

node "$HERE/cli.mjs" build --report "$OUT/agentsim.json" --samples "$OUT/samples.csv" --idle "$OUT/idle.csv" \
  --hardware "$OUT/hardware.json" --stack "$OUT/stack.json" \
  --git-sha "$(git -C "$REPO" rev-parse HEAD)" --profile "$PROFILE" --out "$OUT/kpi.json"
echo "run-perf: wrote $OUT/kpi.json" >&2
