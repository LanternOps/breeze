test('run-perf.sh always tears the stack down, also when a step fails', () => {
  const fx = makeFixture();
  let r = run(fx, 'run-perf.sh', ['--profile', 'nightly-200', '--out-dir', path.join(fx.root, 'ok')]);
  assert.equal(r.code, 0, r.err);
  assert.match(r.log, /pnpm wt-stack up/);
  assert.match(r.log, /pnpm wt-stack down/);
  assert.equal(existsSync(path.join(fx.repo, 'load-tests', 'agentsim', '.state')), false);

  r = run(fx, 'run-perf.sh', ['--profile', 'nightly-200', '--out-dir', path.join(fx.root, 'fail')], { STUB_RUN_FAIL: '1' });
  assert.notEqual(r.code, 0);
  assert.match(r.log, /pnpm wt-stack down/);
  assert.equal(existsSync(path.join(fx.repo, '.env')), false, '.env removed after a failure');
  assert.equal(existsSync(path.join(fx.repo, 'load-tests', 'agentsim', '.state')), false);
  assert.doesNotMatch(r.log, /cli build/, 'no KPI record from a failed simulator run');
});

