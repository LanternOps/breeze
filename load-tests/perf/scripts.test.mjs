test('run-perf.sh hardware fingerprint: macOS fallback is not baseline-grade, Linux reads /proc', () => {
  const fx = makeFixture();
  const mac = path.join(fx.root, 'mac');
  assert.equal(run(fx, 'run-perf.sh', ['--profile', 'smoke', '--out-dir', mac]).code, 0);
  const hw = JSON.parse(readFileSync(path.join(mac, 'hardware.json'), 'utf8'));
  assert.deepEqual(
    { cpuModel: hw.cpuModel, cpus: hw.cpus, memGiB: hw.memGiB, baselineGrade: hw.baselineGrade, dockerVersion: hw.dockerVersion },
    { cpuModel: 'Stub CPU Brand', cpus: 8, memGiB: 32, baselineGrade: false, dockerVersion: '27.0.0' },
  );

  const proc = path.join(fx.root, 'proc');
  mkdirSync(proc);
  writeFileSync(path.join(proc, 'cpuinfo'), 'processor\t: 0\nmodel name\t: Stub Linux CPU @ 2.00GHz\n');
  writeFileSync(path.join(proc, 'meminfo'), 'MemTotal:       16777216 kB\nMemFree: 1 kB\n');
  const linux = path.join(fx.root, 'linux');
  assert.equal(run(fx, 'run-perf.sh', ['--profile', 'smoke', '--out-dir', linux], { STUB_UNAME: 'Linux', PERF_PROC_DIR: proc }).code, 0);
  const lhw = JSON.parse(readFileSync(path.join(linux, 'hardware.json'), 'utf8'));
  assert.deepEqual(
    { cpuModel: lhw.cpuModel, cpus: lhw.cpus, memGiB: lhw.memGiB, baselineGrade: lhw.baselineGrade, kernel: lhw.kernel },
    { cpuModel: 'Stub Linux CPU @ 2.00GHz', cpus: 4, memGiB: 16, baselineGrade: true, kernel: '6.8.0-stub' },
  );
});
