// Stubbed-PATH tests for sample.sh and run-perf.sh. The scripts are copied into a
// throwaway fake repo (they locate the repo from their own path), so nothing here
// touches docker, pnpm, git or a real .env.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { chmodSync, copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const HEADER = 'ts,cpu_seconds,xact_commit,ws_connections,elu,lag_max,pool_waiting,scrape_ok';
const MARKER = '# generated by load-tests/perf/run-perf.sh';

const SCRAPE = [
  'breeze_process_cpu_seconds_total{mode="user"} 12.5',
  'breeze_process_cpu_seconds_total{mode="system"} 2.5',
  'breeze_agent_ws_connections 200',
  'breeze_nodejs_eventloop_utilization 0.31',
  'breeze_nodejs_eventloop_lag_max_seconds 0.012',
  'breeze_db_pool_admission_waiting 2',
  '',
].join('\n');

function script(file, body) {
  writeFileSync(file, body);
  chmodSync(file, 0o755);
}

function makeFixture({ envExample = true } = {}) {
  const root = mkdtempSync(path.join(tmpdir(), 'perf-scripts-'));
  const repo = path.join(root, 'repo');
  const perf = path.join(repo, 'load-tests', 'perf');
  const agentsim = path.join(repo, 'load-tests', 'agentsim');
  const bin = path.join(root, 'bin');
  mkdirSync(perf, { recursive: true });
  mkdirSync(agentsim, { recursive: true });
  mkdirSync(bin, { recursive: true });
  for (const f of ['sample.sh', 'run-perf.sh']) {
    // Missing script => the copy throws and the test fails (the red state).
    copyFileSync(path.join(HERE, f), path.join(perf, f));
    chmodSync(path.join(perf, f), 0o755);
  }
  writeFileSync(path.join(repo, '.breeze-stack.json'), JSON.stringify({ project: 'stubproj', pgContainer: 'stub-pg' }));
  if (envExample) {
    writeFileSync(
      path.join(repo, '.env.example'),
      [
        '# example',
        'POSTGRES_USER=breeze',
        'JWT_SECRET=placeholder-jwt-secret-value',
        'POSTGRES_PASSWORD=placeholder-pg-pass',
        'DATABASE_URL=postgresql://breeze:placeholder-pg-pass@localhost:5432/breeze',
        'AGENT_ENROLLMENT_SECRET=placeholder-enroll-secret',
        'METRICS_SCRAPE_TOKEN=placeholder-metrics-token',
        'ENROLLMENT_KEY_DEFAULT_TTL_MINUTES=43200',
        'RESEND_API_KEY=',
        'FORCE_HTTPS=true',
        '',
      ].join('\n'),
    );
  }
  writeFileSync(
    path.join(perf, 'cli.mjs'),
    "import { appendFileSync, writeFileSync } from 'node:fs';\n" +
      'const a = process.argv.slice(2);\n' +
      "appendFileSync(process.env.STUB_LOG, `cli ${a.join(' ')}\\n`);\n" +
      "writeFileSync(a[a.indexOf('--out') + 1], '{}');\n",
  );
  script(
    path.join(agentsim, 'run.sh'),
    '#!/usr/bin/env bash\n' +
      'echo "run.sh $*" >> "$STUB_LOG"\n' +
      'prev=""; for a in "$@"; do [ "$prev" = --report ] && echo "{}" > "$a"; prev="$a"; done\n' +
      '[ -n "${STUB_RUN_FAIL:-}" ] && exit 1\nexit 0\n',
  );
  script(path.join(agentsim, 'lab-setup.sh'), '#!/usr/bin/env bash\necho "lab-setup" >> "$STUB_LOG"\necho "AGENTSIM_STORE=/stub/store.json"\n');
  script(path.join(agentsim, 'check-acceptance.sh'), '#!/usr/bin/env bash\necho "check-acceptance $*" >> "$STUB_LOG"\nexit "${STUB_ACCEPT_RC:-0}"\n');
  script(
    path.join(bin, 'docker'),
    '#!/usr/bin/env bash\n' +
      'case "$*" in\n' +
      '  "ps "*) echo stub-api ;;\n' +
      '  *"node -e"*) [ -f "$STUB_SCRAPE" ] && cat "$STUB_SCRAPE" ;;\n' +
      '  *psql*) cat > /dev/null; echo "${STUB_XACT-777}" ;;\n' +
      '  "info "*) echo "8 34359738368" ;;\n' +
      '  "version "*) echo 27.0.0 ;;\n' +
      'esac\nexit 0\n',
  );
  script(
    path.join(bin, 'pnpm'),
    '#!/usr/bin/env bash\n' +
      'echo "pnpm $*" >> "$STUB_LOG"\n' +
      'if [ "$1 $2" = "wt-stack up" ]; then\n' +
      '  echo "TOKEN=$METRICS_SCRAPE_TOKEN" >> "$STUB_LOG"\n' +
      '  echo "ENROLL_LIMIT=$AGENT_ENROLL_RATE_LIMIT" >> "$STUB_LOG"\n' +
      '  echo "ADMISSION=$BREEZE_ADMISSION_MODE" >> "$STUB_LOG"\n' +
      '  [ -f .env ] && cp .env "$STUB_ENV_SNAPSHOT"\n' +
      'fi\nexit 0\n',
  );
  script(path.join(bin, 'git'), '#!/usr/bin/env bash\ncase "$*" in *rev-parse*) echo aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa ;; esac\nexit 0\n');
  script(path.join(bin, 'uname'), '#!/usr/bin/env bash\ncase "$1" in -s) echo "${STUB_UNAME:-Darwin}" ;; -r) echo 6.8.0-stub ;; *) echo stub ;; esac\n');
  script(path.join(bin, 'sysctl'), '#!/usr/bin/env bash\necho "Stub CPU Brand"\n');
  script(path.join(bin, 'nproc'), '#!/usr/bin/env bash\necho 4\n');
  const scrapeFile = path.join(root, 'scrape.txt');
  writeFileSync(scrapeFile, SCRAPE);
  return { root, repo, perf, bin, scrapeFile, log: path.join(root, 'stub.log'), envSnapshot: path.join(root, 'env.snapshot') };
}

function run(fx, file, args, extraEnv = {}) {
  writeFileSync(fx.log, '');
  const r = spawnSync('bash', [path.join(fx.perf, file), ...args], {
    encoding: 'utf8',
    env: {
      ...process.env,
      PATH: `${fx.bin}${path.delimiter}${process.env.PATH}`,
      STUB_LOG: fx.log,
      STUB_SCRAPE: fx.scrapeFile,
      STUB_ENV_SNAPSHOT: fx.envSnapshot,
      INTERVAL: '0',
      MAX_SAMPLES: '2',
      IDLE_SECONDS: '0',
      ...extraEnv,
    },
  });
  return { code: r.status, out: r.stdout, err: r.stderr, log: readFileSync(fx.log, 'utf8') };
}

test('sample.sh writes the exact header and numeric rows', () => {
  const fx = makeFixture();
  const csv = path.join(fx.root, 'samples.csv');
  const r = run(fx, 'sample.sh', [csv], { MAX_SAMPLES: '3' });
  assert.equal(r.code, 0, r.err);
  const lines = readFileSync(csv, 'utf8').trim().split('\n');
  assert.equal(lines[0], HEADER);
  assert.equal(lines.length, 4);
  for (const line of lines.slice(1)) {
    const f = line.split(',');
    assert.equal(f.length, 8, line);
    assert.match(f[0], /^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ$/);
    assert.deepEqual(f.slice(1), ['15', '777', '200', '0.31', '0.012', '2', '1']);
  }
});

test('sample.sh writes scrape_ok=0 when the scrape is empty or the xact query fails', () => {
  const fx = makeFixture();
  writeFileSync(fx.scrapeFile, '');
  const csv = path.join(fx.root, 'empty.csv');
  assert.equal(run(fx, 'sample.sh', [csv], { MAX_SAMPLES: '1' }).code, 0);
  const rows = readFileSync(csv, 'utf8').trim().split('\n');
  assert.equal(rows[0], HEADER);
  assert.equal(rows[1].split(',').at(-1), '0');
  assert.match(rows[1], /NaN/);

  writeFileSync(fx.scrapeFile, SCRAPE);
  const csv2 = path.join(fx.root, 'noxact.csv');
  assert.equal(run(fx, 'sample.sh', [csv2], { MAX_SAMPLES: '1', STUB_XACT: '' }).code, 0);
  const row = readFileSync(csv2, 'utf8').trim().split('\n')[1].split(',');
  assert.equal(row.at(-1), '0');
  assert.equal(row[2], 'NaN');
});

