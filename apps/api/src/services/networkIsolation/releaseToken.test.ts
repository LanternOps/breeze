import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createPublicKey, verify } from 'node:crypto';
import { describe, expect, it } from 'vitest';
import {
  RELEASE_TOKEN_DOMAIN, ReleaseTokenKeyError, canonicalReleaseTokenPayload, mintReleaseToken, releaseTokenSigner,
} from './releaseToken';

interface ValidVector { description: string; isolationId: string; generation: number; deviceId: string; notBefore: number; expiresAt: number; payload: string; token: string }
interface VectorFile {
  domain: string;
  testKeys: Record<string, { seedHex: string; publicKeyBase64: string }>;
  context: { now: number };
  valid: ValidVector[];
}

// Shared with the agent (releasetoken_test.go): generated by an independent RFC 8032 implementation.
const VECTORS_FILE = resolve(__dirname, '../../../../../agent/internal/isolation/testdata/release_token_vectors.json');
const vectors = JSON.parse(readFileSync(VECTORS_FILE, 'utf8')) as VectorFile;
const seedA = Buffer.from(vectors.testKeys.a!.seedHex, 'hex').toString('base64');
const envA = { NETWORK_ISOLATION_TOKEN_SIGNING_KEY: seedA };
const IID = '6f1c2d3e-4b5a-4c6d-8e7f-0123456789ab';
const DEV = '1a2b3c4d-5e6f-4a7b-8c9d-0e1f2a3b4c5d';

describe('release token — shared vectors', () => {
  it('uses the domain the agent verifies under', () => {
    expect(RELEASE_TOKEN_DOMAIN).toBe(vectors.domain);
  });

  it('derives the public key the vectors name', () => {
    expect(releaseTokenSigner(envA)?.publicKey).toBe(vectors.testKeys.a!.publicKeyBase64);
  });

  it.each(vectors.valid.map(v => [v.description, v] as const))('mints exactly the vector token: %s', (_d, v) => {
    expect(canonicalReleaseTokenPayload({ isolationId: v.isolationId, generation: v.generation, deviceId: v.deviceId, notBefore: v.notBefore, expiresAt: v.expiresAt })).toBe(v.payload);
    const signer = releaseTokenSigner(envA)!;
    expect(signer.sign({ isolationId: v.isolationId, generation: v.generation, deviceId: v.deviceId, notBefore: v.notBefore, expiresAt: v.expiresAt })).toBe(v.token);
  });
});

describe('releaseTokenSigner', () => {
  it('is null when no key is configured: tokens stay off', () => {
    expect(releaseTokenSigner({})).toBeNull();
    expect(releaseTokenSigner({ NETWORK_ISOLATION_TOKEN_SIGNING_KEY: '' })).toBeNull();
    expect(releaseTokenSigner({ NETWORK_ISOLATION_TOKEN_SIGNING_KEY: '   ' })).toBeNull();
  });

  it.each([
    ['not base64', '!!!!'],
    ['31 bytes', Buffer.alloc(31, 1).toString('base64')],
    ['33 bytes', Buffer.alloc(33, 1).toString('base64')],
    ['url-safe alphabet', Buffer.alloc(32, 0xfb).toString('base64url')],
    ['no padding', Buffer.alloc(32, 1).toString('base64').replace(/=+$/, '')],
  ])('throws on a malformed key (%s) rather than signing with it', (_name, raw) => {
    expect(() => releaseTokenSigner({ NETWORK_ISOLATION_TOKEN_SIGNING_KEY: raw })).toThrow(ReleaseTokenKeyError);
  });

  it('never puts key material in the error', () => {
    const raw = Buffer.alloc(31, 7).toString('base64');
    try { releaseTokenSigner({ NETWORK_ISOLATION_TOKEN_SIGNING_KEY: raw }); expect.unreachable(); }
    catch (error) { expect(String((error as Error).message)).not.toContain(raw); }
  });
});

describe('mintReleaseToken', () => {
  const signer = releaseTokenSigner(envA)!;
  const now = new Date(vectors.context.now * 1000 + 999);

  it('signs the episode, generation and device for the validity window from now', () => {
    const minted = mintReleaseToken(signer, { isolationId: IID, generation: 3, deviceId: DEV, now, validitySeconds: 7200 });
    expect(minted.notBefore.getTime()).toBe(vectors.context.now * 1000);
    expect(minted.expiresAt.getTime()).toBe((vectors.context.now + 7200) * 1000);
    const [payload, sig] = minted.token.split('.');
    expect(JSON.parse(Buffer.from(payload!, 'base64url').toString('utf8'))).toEqual({ v: 1, iid: IID, gen: 3, dev: DEV, nbf: vectors.context.now, exp: vectors.context.now + 7200 });
    const spki = Buffer.concat([Buffer.from('302a300506032b6570032100', 'hex'), Buffer.from(signer.publicKey, 'base64')]);
    const key = createPublicKey({ key: spki, format: 'der', type: 'spki' });
    expect(verify(null, Buffer.from(RELEASE_TOKEN_DOMAIN + payload, 'utf8'), key, Buffer.from(sig!, 'base64url'))).toBe(true);
  });

  it('lowercases the episode and device ids it binds', () => {
    const minted = mintReleaseToken(signer, { isolationId: IID.toUpperCase(), generation: 3, deviceId: DEV.toUpperCase(), now, validitySeconds: 60 });
    const payload = JSON.parse(Buffer.from(minted.token.split('.')[0]!, 'base64url').toString('utf8'));
    expect(payload.iid).toBe(IID);
    expect(payload.dev).toBe(DEV);
  });

  it.each([
    ['isolation id', { isolationId: 'not-a-uuid' }],
    ['device id', { deviceId: '' }],
    ['generation 0', { generation: 0 }],
    ['fractional generation', { generation: 1.5 }],
    ['zero validity', { validitySeconds: 0 }],
    ['validity over 24 h', { validitySeconds: 86_401 }],
    ['invalid now', { now: new Date(Number.NaN) }],
  ])('refuses a bad %s', (_name, override) => {
    expect(() => mintReleaseToken(signer, { isolationId: IID, generation: 3, deviceId: DEV, now, validitySeconds: 7200, ...override })).toThrow();
  });
});
