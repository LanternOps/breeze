/**
 * Tool Catalog W06 (#5221) Task A4 — the automation-style alert writer: one
 * alert row on a device under the org's synthetic "Automation Action Alerts"
 * rule, plus its `alert.triggered` event. Moved verbatim out of
 * automationRuntime's `executeCreateAlertAction` so the legacy action and the
 * flow `create_alert` built-in write identical rows.
 *
 * Provenance decides only the attribution: a legacy action keeps
 * `automationId`/`automationRunId` (the AI-agent class-A loop guard reads
 * `automationId` from the event); a flow keeps `flowRunId` and never an
 * `automationId`.
 *
 * DB: runs in the CALLER's ambient context (the legacy run's context; the flow
 * principal's run-org context). Alert rows take the DEVICE's org (playbook
 * rule 5); the caller has already checked the device belongs to `orgId`.
 */
import { randomUUID } from 'crypto';
import { and, eq } from 'drizzle-orm';
import { db } from '../db';
import { alertRules, alerts, alertTemplates } from '../db/schema';
import { publishEvent } from './eventBus';

export type AutomationStyleAlertProvenance =
  | { kind: 'automation'; automationId: string; runId: string }
  | { kind: 'flow'; flowRunId: string };

export interface AutomationStyleAlertInput {
  orgId: string;
  deviceId: string;
  severity: 'critical' | 'high' | 'medium' | 'low' | 'info';
  title: string;
  message: string;
  provenance: AutomationStyleAlertProvenance;
}

export async function ensureAutomationAlertRule(orgId: string): Promise<string> {
  const templateName = 'Automation Action Template';
  const ruleName = 'Automation Action Alerts';

  const [existingTemplate] = await db
    .select({ id: alertTemplates.id })
    .from(alertTemplates)
    .where(and(eq(alertTemplates.orgId, orgId), eq(alertTemplates.name, templateName)))
    .limit(1);

  const templateId = existingTemplate?.id ?? (await db
    .insert(alertTemplates)
    .values({
      orgId,
      name: templateName,
      description: 'Template for alerts generated by automation actions',
      conditions: {},
      severity: 'medium',
      titleTemplate: '{{title}}',
      messageTemplate: '{{message}}',
      autoResolve: false,
      cooldownMinutes: 1,
      isBuiltIn: false,
    })
    .returning({ id: alertTemplates.id })
  )[0]?.id;

  if (!templateId) {
    throw new Error('Failed to create automation alert template');
  }

  const [existingRule] = await db
    .select({ id: alertRules.id })
    .from(alertRules)
    .where(
      and(
        eq(alertRules.orgId, orgId),
        eq(alertRules.name, ruleName),
        eq(alertRules.targetType, 'org'),
        eq(alertRules.targetId, orgId),
      ),
    )
    .limit(1);

  if (existingRule?.id) {
    return existingRule.id;
  }

  const [rule] = await db
    .insert(alertRules)
    .values({
      orgId,
      templateId,
      name: ruleName,
      targetType: 'org',
      targetId: orgId,
      overrideSettings: {
        templateOwned: true,
      },
      isActive: true,
    })
    .returning({ id: alertRules.id });

  if (!rule?.id) {
    throw new Error('Failed to create automation alert rule');
  }

  return rule.id;
}


/** Null when the insert returned no row (nothing was published). */
export async function createAutomationStyleAlert(input: AutomationStyleAlertInput): Promise<{ alertId: string } | null> {
  const ruleId = await ensureAutomationAlertRule(input.orgId);

  // Every create_alert action shares ONE synthetic per-org rule, so several can
  // be open on one device at once. Each alert is its own subject: the open-alert
  // identity index (one open alert per rule, device, subject — W03 #6854) must
  // never merge distinct automation alerts. The 110300 migration keys existing
  // rows with the same `automation-alert:<id>` form.
  const alertId = randomUUID();
  const attribution = input.provenance.kind === 'automation'
    ? { automationId: input.provenance.automationId, automationRunId: input.provenance.runId }
    : { flowRunId: input.provenance.flowRunId };
  const [createdAlert] = await db
    .insert(alerts)
    .values({
      id: alertId,
      subjectKey: `automation-alert:${alertId}`,
      ruleId,
      deviceId: input.deviceId,
      orgId: input.orgId,
      status: 'active',
      severity: input.severity,
      title: input.title,
      message: input.message,
      context: { ...attribution, deviceId: input.deviceId },
      triggeredAt: new Date(),
    })
    .returning({ id: alerts.id });

  if (!createdAlert?.id) return null;

  await publishEvent(
    'alert.triggered',
    input.orgId,
    {
      alertId: createdAlert.id,
      ruleId,
      deviceId: input.deviceId,
      severity: input.severity,
      title: input.title,
      message: input.message,
      ...(input.provenance.kind === 'automation'
        ? { automationId: input.provenance.automationId, runId: input.provenance.runId }
        : { flowRunId: input.provenance.flowRunId }),
    },
    input.provenance.kind === 'automation' ? 'automation-executor' : 'flow-executor',
  );

  return { alertId: createdAlert.id };
}
