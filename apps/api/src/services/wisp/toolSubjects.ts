const GUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function subjectRefsOf(toolName: string, input: Record<string, unknown>): Array<{ kind: WispEntityKind; id: string }> {
  const subjects = Object.hasOwn(WISP_TOOL_SUBJECTS, toolName) ? WISP_TOOL_SUBJECTS[toolName] : undefined;
  const seen = new Set<string>();
  const refs: Array<{ kind: WispEntityKind; id: string }> = [];
  for (const subject of subjects ?? []) {
    if (subject.actions && (typeof input.action !== 'string' || !subject.actions.includes(input.action))) continue;
    const value = input[subject.arg];
    if (typeof value !== 'string' || !GUID.test(value)) continue;
    const id = value.toLowerCase();
    const key = `${subject.kind}:${id}`;
    if (seen.has(key)) continue;
    seen.add(key);
    refs.push({ kind: subject.kind, id });
  }
  return refs;
}
