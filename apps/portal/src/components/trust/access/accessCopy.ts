/** Locale for pages with no payload (verify/download): first exact match in navigator.languages, else 'en'. */
export function detectAccessLocale(): SupportedLocale {
  const langs = typeof navigator !== 'undefined' ? navigator.languages ?? [] : [];
  for (const l of langs) {
    if ((SUPPORTED_LOCALES as readonly string[]).includes(l)) return l as SupportedLocale;
  }
  return 'en';
}
