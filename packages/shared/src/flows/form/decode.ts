import { ALERT_SEVERITIES } from '../../constants';
import type { DeploymentTargetConfig } from '../../types/filters';
import { deploymentTargetConfigSchema } from '../../validators/filters';
import type { FlowDocumentV1 } from '../../validators/flows';
import { TRIGGER_DEVICE_SELECTOR } from './compile';
import { deviceCountsSuffix, type FlowStep } from './emit';
import type { FlowFormAction, FlowFormFailureNotice, FlowFormOnFailure, FlowFormTarget, FlowFormTrigger, FlowFormValues } from './types';

const ID_RE = /^a(\d+)_(run_script|devices|alert|failed|notify|failnotice_(\d+)|failsummary_(\d+))$/;
const NOTIFY_SEVERITIES = ['info', 'warning', 'critical'] as const;

function isRecord(v: unknown): v is Record<string, unknown> {
  return v !== null && typeof v === 'object' && !Array.isArray(v);
}
function isParams(v: unknown): v is Record<string, string | number | boolean> {
  return isRecord(v) && Object.values(v).every((x) => ['string', 'number', 'boolean'].includes(typeof x));
}
const isTriggerDeviceSelector = (v: unknown): boolean =>
  isRecord(v) && Object.keys(v).length === 1 && Array.isArray(v.deviceIds)
  && v.deviceIds.length === 1 && v.deviceIds[0] === TRIGGER_DEVICE_SELECTOR.deviceIds[0];

function decodeTrigger(t: FlowDocumentV1['trigger']): FlowFormTrigger | null {
  switch (t.type) {
    case 'schedule': return { type: 'schedule', cron: t.cron, timezone: t.timezone };
    case 'event': {
      const filter: Record<string, string | number | boolean> = {};
      for (const [k, v] of Object.entries(t.filter)) {
        if (v === null) return null; // a null filter value has no form control
        filter[k] = v;
      }
      return { type: 'event', event: t.event, filter };
    }
    case 'webhook': return t.orgResolver ? { type: 'webhook', auth: t.auth, orgResolver: t.orgResolver } : { type: 'webhook', auth: t.auth };
    case 'manual': return { type: 'manual' };
  }
}

/**
 * The selector a step carries: the triggering device, a literal target, or
 * `undefined` when the step chains on an earlier set. `null` when the input
 * is something the form cannot express (legacy conditions, other device ids).
 */
function selectorOf(input: Record<string, unknown>, triggerType: FlowFormTrigger['type']): FlowFormTarget | undefined | null {
  if (input.fromStep !== undefined) return undefined;
  // Only an event payload can name a device: on any other trigger `{{trigger.device.id}}` resolves to nothing.
  if (isTriggerDeviceSelector({ deviceIds: input.deviceIds })) return triggerType === 'event' ? { kind: 'trigger_device' } : null;
  if (isRecord(input.target)) {
    // A target the picker cannot show (unknown type, malformed filter) is not form-editable.
    const parsed = deploymentTargetConfigSchema.safeParse(input.target);
    return parsed.success ? { kind: 'target', target: parsed.data as DeploymentTargetConfig } : null;
  }
  return null;
}

/**
 * Reads a document back into guided-form values, or `null` when the steps do
 * not follow the shapes `compileFlowForm` emits. It is a positional parse and
 * deliberately lenient: it never claims a document is form-shaped by itself.
 * `recognizeFlowForm` decides that by recompiling the result and comparing.
 */
export function decodeFlowForm(doc: FlowDocumentV1): FlowFormValues | null {
  const trigger = decodeTrigger(doc.trigger);
  if (!trigger) return null;

  const actions: FlowFormAction[] = [];
  const failureChannels: string[] = [];
  let sawFailureBlock = false;
  // The notice shape the failure steps carry. A document with both shapes (in
  // one block or across scripts) has no single form value, so it does not decode.
  let failureNotice = null as FlowFormFailureNotice | null; // `as`: set inside noteShape, so keep TS from narrowing it to null
  const noteShape = (shape: FlowFormFailureNotice): boolean => {
    if (failureNotice !== null && failureNotice !== shape) return false;
    failureNotice = shape;
    return true;
  };
  let usesDispatched = false;
  let target: FlowFormTarget | undefined;
  let lastScriptStepId: string | null = null;

  const setTarget = (t: FlowFormTarget | undefined | null): boolean => {
    if (t === null) return false;
    if (t !== undefined && !target) target = t;
    return true;
  };

  for (const step of doc.steps as FlowStep[]) {
    if (step.id === 'targets') {
      if (step.tool !== 'resolve_targets' || !setTarget(selectorOf(step.input, trigger.type))) return null;
      continue;
    }
    const m = ID_RE.exec(step.id);
    if (!m) return null;
    const i = Number(m[1]);
    const kind = m[2]!;
    const input = step.input;

    if (kind === 'failed' && !noteShape('perDevice')) return null;
    if (kind === 'devices' || kind === 'failed') {
      // Regenerated by compile and verified by the recompile; only the chain set carries a form value.
      if (kind === 'devices' && isRecord(input.fromStep) && input.fromStep.set === 'dispatched') usesDispatched = true;
      continue;
    }

    if (kind === 'run_script') {
      if (i !== actions.length || step.tool !== 'run_script_on_targets') return null;
      if (typeof input.scriptId !== 'string') return null;
      if (!setTarget(selectorOf(input, trigger.type))) return null;
      if (isRecord(input.fromStep) && input.fromStep.set === 'dispatched') usesDispatched = true;
      const action: FlowFormAction = {
        type: 'run_script',
        scriptId: input.scriptId,
        whenOffline: input.whenOffline === 'skip' ? 'skip' : 'queue',
      };
      if (input.parameters !== undefined) {
        if (!isParams(input.parameters)) return null;
        action.parameters = input.parameters;
      }
      if (input.runAs === 'system' || input.runAs === 'user') action.runAs = input.runAs;
      else if (input.runAs !== undefined) return null;
      actions.push(action);
      lastScriptStepId = step.id;
      continue;
    }

    if (kind.startsWith('failnotice_') || kind.startsWith('failsummary_')) {
      if (!noteShape(kind.startsWith('failsummary_') ? 'summary' : 'perDevice')) return null;
      sawFailureBlock = true;
      if (step.tool !== 'notify' || typeof input.channelId !== 'string') return null;
      if (!actions.length || !(actions[actions.length - 1]!.type === 'run_script')) return null;
      // Every script carries the same channel list; read it once, from the first block.
      if (i === actions.findIndex((a) => a.type === 'run_script')) failureChannels.push(input.channelId);
      continue;
    }

    if (kind === 'alert') {
      if (i !== actions.length || step.tool !== 'create_alert') return null;
      const { severity, title, message } = input;
      if (typeof severity !== 'string' || !(ALERT_SEVERITIES as readonly string[]).includes(severity)) return null;
      if (typeof title !== 'string' || typeof message !== 'string') return null;
      actions.push({ type: 'create_alert', severity: severity as (typeof ALERT_SEVERITIES)[number], title, message });
      continue;
    }

    // notify: one step for the whole run, no for-each.
    if (i !== actions.length || step.tool !== 'notify' || step.forEach !== undefined) return null;
    const { channelId, title, severity, message: rawMessage } = input;
    if (typeof channelId !== 'string' || typeof title !== 'string' || typeof rawMessage !== 'string') return null;
    let message: string = rawMessage;
    if (typeof severity !== 'string' || !(NOTIFY_SEVERITIES as readonly string[]).includes(severity)) return null;
    if (lastScriptStepId) {
      const suffix = deviceCountsSuffix(lastScriptStepId);
      if (message.endsWith(suffix)) message = message.slice(0, -suffix.length);
    }
    actions.push({ type: 'notify', channelId, title, message, severity: severity as (typeof NOTIFY_SEVERITIES)[number] });
  }

  // A notify-only document names no selector; the form holds what each trigger implies.
  const resolvedTarget: FlowFormTarget = target
    ?? (trigger.type === 'event' ? { kind: 'trigger_device' } : { kind: 'target', target: { type: 'all' } });

  const onFailure: FlowFormOnFailure = sawFailureBlock
    ? { mode: 'notify', channelIds: failureChannels, notice: failureNotice ?? 'perDevice' }
    : { mode: usesDispatched ? 'continue' : 'stop' };

  return {
    name: doc.name,
    ...(doc.description !== undefined ? { description: doc.description } : {}),
    trigger,
    target: resolvedTarget,
    actions,
    onFailure,
  };
}
