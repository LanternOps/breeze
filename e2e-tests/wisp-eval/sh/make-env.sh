#!/usr/bin/env bash
# make-env.sh <path-to-populated-.env> [caddy-port] [docker-subnet]
#
# Writes <repo root>/.env for a throwaway wt-stack that talks to a REAL model.
# What happens to each key of the source file:
#
#   carried over  ANTHROPIC_API_KEY (CARRY). The only secret taken from the source.
#   generated     the stack's own secrets (GEN_HEX, GEN_B64): a fresh `openssl rand`
#                 value per key, never the source's value.
#   blanked       secrets the stack boots without (STACK_BLANK: the JWT keyring, the
#                 OAuth keys while MCP_OAUTH_ENABLED=false, the audit anchor key, the
#                 bootstrap and e2e admin passwords, so the seed uses the dev admin
#                 password that .breeze-stack.json logs in with); the fixed list of
#                 outside-service settings (BLANK); and every other key whose NAME
#                 looks like a credential (KEY, TOKEN, SECRET, DSN, PASSWORD, ...) or
#                 whose VALUE is a URL with a password in it. A credential added to the
#                 source later is blanked by default.
#   copied        everything else: settings, image refs, and public keys (PUBLIC).
#   set           the Wisp feature flags and the stack's port, subnet and caddy IP (SET).
#
# Re-running over a .env this script wrote reuses the values it generated there (so a
# stack whose volumes were kept still decrypts its data and accepts its passwords).
# A previous value is reused only if it has the expected format and differs from the
# source's value; anything else is generated again.
#
# Port and subnet come from the arguments, else BREEZE_WT_CADDY_PORT /
# BREEZE_DOCKER_SUBNET, else 48378 / 172.31.78.0/24. The caddy IP is .10 in the
# subnet unless BREEZE_CADDY_IP is set.
#
# Never prints a value; it prints key names only. Working files live in a private
# temp directory (mode 700, removed on exit). The result is staged beside the
# destination as .tmp-wisp-eval-env.* (gitignored) and renamed into place, so the
# destination is never left half-written. Refuses to overwrite a .env it did not
# write (FORCE=1 overrides) and refuses to read and write the same file.
set -euo pipefail
umask 077

SRC="${1:-}"
[ -n "$SRC" ] && [ -f "$SRC" ] || { echo "usage: make-env.sh <path-to-populated-.env> [caddy-port] [docker-subnet]" >&2; exit 2; }
command -v openssl >/dev/null || { echo "make-env.sh: openssl is required" >&2; exit 2; }

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../../.." && pwd)"
# WISP_EVAL_ENV_DEST redirects the output (make-env.test.cjs writes to a temp dir).
DEST="${WISP_EVAL_ENV_DEST:-$ROOT/.env}"
MARKER="# generated by e2e-tests/wisp-eval/sh/make-env.sh"
GEN_HEADER="# --- generated for this stack ---"

PORT="${2:-${BREEZE_WT_CADDY_PORT:-48378}}"
SUBNET="${3:-${BREEZE_DOCKER_SUBNET:-172.31.78.0/24}}"
case "$SUBNET" in
  */24) ;;
  *) echo "make-env.sh: subnet must be a /24 (got $SUBNET)" >&2; exit 2 ;;
esac
CADDY_IP="${BREEZE_CADDY_IP:-${SUBNET%.*}.10}"
case "$PORT" in ''|*[!0-9]*) echo "make-env.sh: port must be numeric" >&2; exit 2 ;; esac

src_real="$(cd "$(dirname "$SRC")" && pwd)/$(basename "$SRC")"
if [ "$src_real" = "$DEST" ]; then
  echo "make-env.sh: source and destination are the same file ($DEST); pass the populated .env of another checkout" >&2
  exit 2
fi
reuse=0
if [ -e "$DEST" ]; then
  if grep -qxF "$MARKER" "$DEST"; then reuse=1
  elif [ "${FORCE:-0}" != "1" ]; then
    echo "make-env.sh: $DEST exists and was not written by this script; move it away or set FORCE=1" >&2
    exit 2
  fi
fi

grep -q '^ANTHROPIC_API_KEY=..' "$SRC" || echo "make-env.sh: warning: the source has no ANTHROPIC_API_KEY value; Wisp will not answer" >&2

# The one secret taken from the source.
CARRY="ANTHROPIC_API_KEY"
# Not secrets, though their names match the credential pattern: copied as they are.
PUBLIC="RELEASE_ARTIFACT_MANIFEST_PUBLIC_KEYS"
# The stack's own secrets, generated per stack. 32 random bytes as hex suits every one
# of these (the API's production format for the encryption keys; no shell or compose
# quoting needed). The partner API cursor key must be canonical base64 of 32 bytes.
# .env.stack (wt-stack) pins POSTGRES_PASSWORD, both peppers and TURN_SECRET to its dev
# values and wins over this file; they are generated here anyway so no source value
# is written.
GEN_HEX="JWT_SECRET APP_ENCRYPTION_KEY MFA_ENCRYPTION_KEY MFA_RECOVERY_CODE_PEPPER ENROLLMENT_KEY_PEPPER AGENT_ENROLLMENT_SECRET POSTGRES_PASSWORD REDIS_PASSWORD BREEZE_APP_DB_PASSWORD TURN_SECRET SESSION_SECRET METRICS_SCRAPE_TOKEN"
GEN_B64="PARTNER_API_CURSOR_SIGNING_KEY"
# Secrets the stack boots without. JWT_SECRET signs alone without a keyring, and a
# JWT_ACTIVE_KID without a keyring fails validation. The OAuth keys are only read when
# MCP_OAUTH_ENABLED=true. Without AUDIT_ANCHOR_SIGNING_KEY anchors are written unsigned.
# Without a bootstrap password the seed uses the dev admin password, which is the one
# wt-stack puts in .breeze-stack.json for setup.sh to log in with. E2E_ADMIN_PASSWORD
# is not read by the API; `wt-stack test` passes the descriptor's password itself.
STACK_BLANK="JWT_SIGNING_KEYRING JWT_ACTIVE_KID OAUTH_COOKIE_SECRET OAUTH_JWKS_PRIVATE_JWK OAUTH_JWKS_PUBLIC_JWK AUDIT_ANCHOR_SIGNING_KEY BREEZE_BOOTSTRAP_ADMIN_PASSWORD E2E_ADMIN_PASSWORD"
# Outside-service settings blanked by name (some do not match the credential pattern).
BLANK="OPENAI_API_KEY EMAIL_PROVIDER RESEND_API_KEY STRIPE_SECRET_KEY STRIPE_WEBHOOK_SECRET BILLING_SERVICE_API_KEY BREEZE_BILLING_URL NVD_API_KEY PUBLIC_ACTIVATION_BASE_URL"
SET="FORCE_HTTPS=false
TRUST_PROXY_HEADERS=false
MCP_OAUTH_ENABLED=false
NODE_ENV=development
BREEZE_WORKSPACE_ENABLED=false
BREEZE_WISP_ENABLED=true
BREEZE_AI_AGENTS_ENABLED=true
BREEZE_AI_AGENTS_POLICY_DECIDE_ENABLED=true
MCP_TIER3_INTENTS_ENABLED=true
TOOL_SOURCES_ENABLED=true
AI_OPERATOR_TASKS_ENABLED=true
FLOWS_ENABLED=true
MFA_FORCE_FOR_PARTNER_ADMIN=false
AGENT_ENROLL_RATE_LIMIT=5000
CORS_ALLOWED_ORIGINS=http://localhost:$PORT
BREEZE_DOCKER_SUBNET=$SUBNET
BREEZE_CADDY_IP=$CADDY_IP"

# Every key we generate, blank or set is dropped from the copy, then appended once.
DROP="$GEN_HEX $GEN_B64 $STACK_BLANK $BLANK $(printf '%s\n' "$SET" | cut -d= -f1 | tr '\n' ' ')"

work="$(mktemp -d "${TMPDIR:-/tmp}/wisp-eval-env.XXXXXX")"
chmod 700 "$work"
stage=""
cleanup() { rm -rf "$work"; [ -z "$stage" ] || rm -f "$stage"; }
trap cleanup EXIT
blanked="$work/blanked"
: > "$blanked"

# value_of FILE KEY [SECTION] — the last value of KEY in FILE (only inside SECTION when given).
value_of() {
  awk -v k="$2" -v sec="${3:-}" '
    sec != "" && $0 == sec { in_sec = 1; next }
    sec != "" && /^# ---/ { in_sec = 0 }
    sec != "" && !in_sec { next }
    { line = $0; sub(/^[[:space:]]*export[[:space:]]+/, "", line) }
    index(line, k "=") == 1 { v = substr(line, length(k) + 2) }
    END { printf "%s", v }
  ' "$1"
}

# secret KEY FORMAT — reuse the previous generated value when it is valid, else generate.
secret() {
  local k="$1" fmt="$2" prev="" re
  case "$fmt" in hex) re='[0-9a-f]{64}' ;; b64) re='[A-Za-z0-9+/]{43}=' ;; esac
  if [ "$reuse" = 1 ]; then prev="$(value_of "$DEST" "$k" "$GEN_HEADER")"; fi
  if [ -n "$prev" ] && [ "$prev" != "$(value_of "$SRC" "$k")" ] && printf '%s' "$prev" | grep -qxE "$re"; then
    printf '%s' "$prev"
    return
  fi
  case "$fmt" in
    hex) openssl rand -hex 32 ;;
    b64) openssl rand -base64 32 ;;
  esac
}

out="$work/env"
{
  echo "$MARKER"
  echo "# source: $(basename "$SRC") (values not shown); regenerate instead of editing"
  # Copy every key that is not dropped. A key that is neither carried over nor public,
  # and whose name looks like a credential or whose value is a URL with a password, goes
  # to $blanked instead. Names that only look like one (ENROLLMENT_KEY_DEFAULT_TTL_MINUTES,
  # APP_ENCRYPTION_KEY_ID) are settings and are copied.
  awk -v drop="$DROP" -v keep="$CARRY $PUBLIC" -v blanked="$blanked" '
    function secretlike(k) {
      if (k ~ /(_MINUTES|_SECONDS|_DAYS|_LIMIT|_ENABLED|_VERSION|_KEY_ID|_PER_[A-Z_]+|_MODE)$/) return 0
      return k ~ /(KEY|TOKEN|SECRET|DSN|PASSWORD|CREDENTIAL|PRIVATE|WEBHOOK_URL)/
    }
    BEGIN {
      n = split(drop, d, " "); for (i = 1; i <= n; i++) if (d[i] != "") skip[d[i]] = 1
      n = split(keep, k, " "); for (i = 1; i <= n; i++) if (k[i] != "") keepk[k[i]] = 1
    }
    /^[[:space:]]*#/ || !/=/ { next }
    {
      key = $0; sub(/=.*/, "", key); sub(/^[[:space:]]*export[[:space:]]+/, "", key)
      val = $0; sub(/^[^=]*=/, "", val)
      if (key in skip) next
      if (!(key in keepk) && (key ~ /^MSI_SIGNING_/ || secretlike(key) || val ~ /:\/\/[^\/@[:space:]]+:[^\/@[:space:]]*@/)) { print key > blanked; next }
      print
    }
  ' "$SRC"
  echo "$GEN_HEADER"
  for k in $GEN_HEX; do printf '%s=%s\n' "$k" "$(secret "$k" hex)"; done
  for k in $GEN_B64; do printf '%s=%s\n' "$k" "$(secret "$k" b64)"; done
  echo "# --- blanked: the stack boots without these ---"
  for k in $STACK_BLANK; do echo "$k="; done
  echo "# --- wisp-eval overrides ---"
  for k in $BLANK; do echo "$k="; done
  printf '%s\n' "$SET"
  echo "# --- blanked by name or value pattern ---"
  sort -u "$blanked" | sed 's/$/=/'
} > "$out"

# `secret` runs in a subshell above, so count reuse here from the result.
generated=0 reused=0
for k in $GEN_HEX $GEN_B64; do
  generated=$((generated + 1))
  [ "$reuse" = 1 ] || continue
  prev="$(value_of "$DEST" "$k" "$GEN_HEADER")"
  if [ -n "$prev" ] && [ "$prev" = "$(value_of "$out" "$k" "$GEN_HEADER")" ]; then reused=$((reused + 1)); fi
done
prev=""

stage="$(mktemp "$(dirname "$DEST")/.tmp-wisp-eval-env.XXXXXX")"
chmod 600 "$stage"
cat "$out" > "$stage"
mv -f "$stage" "$DEST"
stage=""
names="$(sort -u "$blanked" | tr '\n' ' ')"

echo "wrote $DEST (mode 600): $(grep -c '=' "$DEST") keys; caddy port $PORT, subnet $SUBNET, caddy ip $CADDY_IP"
echo "carried over ANTHROPIC_API_KEY: $(grep -q '^ANTHROPIC_API_KEY=..' "$DEST" && echo yes || echo NO)"
echo "generated $generated stack secrets ($reused reused from the previous output): $GEN_HEX $GEN_B64"
echo "blanked, the stack boots without them: $STACK_BLANK"
echo "blanked by name or value pattern (outside-service credentials): ${names:-none}"
